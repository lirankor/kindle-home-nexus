export const DEFAULT_LANG: Lang = "he";
export const parseLang = (value: string | undefined | null): Lang =>
  value?.trim().toLowerCase().startsWith("en") ? "en" : DEFAULT_LANG;
export const isRtl = (lang: Lang) => lang === "he";
export const dateLocale = (lang: Lang) => (lang === "he" ? "he-IL" : "en-GB");

