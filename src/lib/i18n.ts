export const dictionaries: Record<Lang, Record<Key, string>> = { en, he };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;
export const makeT =
  (lang: Lang): TFn =>
  (key, vars) =>
    (dictionaries[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) =>
      String(vars?.[name] ?? ""),
    );

/** Translate a key only when it exists (state and weather ids come from Home Assistant). */
export const tryT = (lang: Lang, key: string): string | null =>
  key in en ? makeT(lang)(key as Key) : null;
